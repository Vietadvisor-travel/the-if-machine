#!/usr/bin/env python3
"""Import an SVG icon pack into the engine: python3 tools/icons.py <folder of .svg> <pack> [--fill]
   → engine/library/ifm_icons_<pack>.js (generated, gitignored; setup.sh rebuilds it). Licence must be CC0 / MIT / ISC / OFL-like.
   Use: IFM.icon('<pack>:<name>', x, y, size, colour)  ·  bank id 'icon:<pack>:<name>' in act=stage."""
import sys, os, re, json, glob
src, pack = sys.argv[1], sys.argv[2]; out = {}
_first = next(iter(sorted(glob.glob(os.path.join(src, '*.svg')))), None); _t = open(_first, encoding='utf-8').read() if _first else ''
fill = '--fill' in sys.argv or ('--stroke' not in sys.argv and not re.search(r'<svg[^>]*fill="none"', _t))   # auto: line packs set fill="none" on <svg>
num = lambda s, d=0: float(s) if s not in (None, '') else d
for f in sorted(glob.glob(os.path.join(src, '*.svg'))):
    t = open(f, encoding='utf-8').read(); vb = re.search(r'viewBox="([\d.\s-]+)"', t); vb = [float(x) for x in vb.group(1).split()] if vb else [0, 0, 24, 24]; ds = []
    for m in re.finditer(r'<path([^>]*)/?>', t):
        a = m.group(1)
        if 'stroke="none"' in a and 'fill="none"' in a: continue
        d = re.search(r'\sd="([^"]+)"', a); ds.append(d.group(1)) if d else None
    for m in re.finditer(r'<circle([^>]*)/?>', t):
        g = dict(re.findall(r'(\w+)="([^"]*)"', m.group(1))); cx, cy, r = num(g.get('cx')), num(g.get('cy')), num(g.get('r'))
        ds.append(f'M{cx - r} {cy}a{r} {r} 0 1 0 {2 * r} 0a{r} {r} 0 1 0 {-2 * r} 0')
    for m in re.finditer(r'<rect([^>]*)/?>', t):
        g = dict(re.findall(r'(\w+)="([^"]*)"', m.group(1))); x, y, w, h = num(g.get('x')), num(g.get('y')), num(g.get('width')), num(g.get('height')); ds.append(f'M{x} {y}h{w}v{h}h{-w}z')
    for m in re.finditer(r'<line([^>]*)/?>', t):
        g = dict(re.findall(r'(\w+)="([^"]*)"', m.group(1))); ds.append(f"M{num(g.get('x1'))} {num(g.get('y1'))}L{num(g.get('x2'))} {num(g.get('y2'))}")
    for m in re.finditer(r'<poly(line|gon)([^>]*)/?>', t):
        pts = re.search(r'points="([^"]+)"', m.group(2)); ds.append('M' + pts.group(1).strip() + ('z' if m.group(1) == 'gon' else '')) if pts else None
    if ds: out[os.path.splitext(os.path.basename(f))[0]] = [vb[2], '|'.join(ds)]
js = f"/* generated by tools/icons.py from {os.path.basename(os.path.abspath(src))} — {len(out)} icons */\nwindow.IFM_ICONS = window.IFM_ICONS || {{}}; IFM_ICONS[{json.dumps(pack)}] = {{ fill: {str(fill).lower()}, icons: {json.dumps(out, separators=(',', ':'))} }};\n"
dst = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'engine', 'library', f'ifm_icons_{pack}.js'); open(dst, 'w').write(js); print(dst, len(out), 'icons', round(len(js) / 1e6, 2), 'MB')
