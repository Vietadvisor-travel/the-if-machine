#!/usr/bin/env python3
"""The drawing library catalog (owner, 15 Nov 2026: each film draws its own things; the library GROWS from the films, it is not a kit).
  python3 tools/lib_index.py   → library.json (every drawable: kind core|tool|sample|episode, origin) + src/lib/index.ts (episode drawings wired in)
kinds: core = generic by nature (paper, sky, Earth/Moon/Sun as real bodies, real-stock frames, diagram marks) → free to use in any film ·
tool = a construction system (Person rig) → every use needs this film's own design · sample = a reference drawing (src/paint/) → NEVER
in a film as is: draw the film's own version · episode = drawn for a film (src/lib/<slug>/) → reused in another film only when it is the
SAME real thing, with a reason in that film's episode.json `reuse`."""
import json, os, re, glob
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'); os.chdir(R)
CORE = ['Sky', 'Stars', 'Sun', 'Moon', 'Earth', 'Pinned', 'DocumentPage', 'Eyepiece', 'FilmStrip', 'Loupe', 'Clipping', 'CabinetCard', 'Angle', 'GoldBeam', 'ShadowCone', 'BloodWash', 'SeaChart', 'Water', 'Ridge', 'Ident', 'EndCard', 'TitleCard']
TOOL = ['Person']
ent = open('src/engine/Entities.tsx').read()
base = re.findall(r'(\w+): (?:Wd|Pl|Id)\.\w+', ent) + ['Person']
lib = {}
for n in base: lib[n] = {'kind': 'core' if n in CORE else 'tool' if n in TOOL else 'sample', 'origin': 'library v3 (src/paint/)'}
imports, maps, costumes, eps = [], [], [], {}
for f in sorted(glob.glob('src/lib/*/index.tsx')):
    slug = f.split('/')[2]
    if slug.startswith('_'): continue
    v = re.sub(r'\W', '_', slug); src = open(f).read()
    imports.append(f"import * as {v} from './{slug}';"); maps.append(v); eps[slug] = v
    m = re.search(r'export const ART[^=]*=\s*\{([^}]*)\}', src, re.S)
    for n in re.findall(r'(\w+)\s*:', m.group(1) if m else ''):
        if n in lib and lib[n].get('origin') != slug: raise SystemExit(f'name clash: {n} ({slug}) already exists ({lib[n]["origin"]}) — pick a unique name')
        lib[n] = {'kind': 'episode', 'origin': slug}
    c = re.search(r'export const COSTUMES[^=]*=\s*\{(.*?)\n\};', src, re.S)
    for n in re.findall(r'^\s*(\w+)\s*:', c.group(1) if c else '', re.M): lib['costume:' + n] = {'kind': 'episode', 'origin': slug}
for n in ('chiton', 'robe', 'coat18', 'frock19', 'labcoat', 'uniform', 'suit', 'spacesuit'): lib['costume:' + n] = {'kind': 'sample', 'origin': 'people.tsx presets'}
open('src/lib/index.ts', 'w').write('// GENERATED by tools/lib_index.py — every film\'s own drawings, wired into the engine. Do not edit.\n' + '\n'.join(imports) +
  "\nexport const LIB_EP: Record<string, any> = { " + ", ".join(f"'{k}': {v}" for k, v in eps.items()) + " };   // slug → module (ART, COSTUMES, SAMPLE)" +
  f"\nexport const LIB_ART: Record<string, any> = Object.assign({{}}, {', '.join(m + '.ART' for m in maps) or '{}'});\nexport const LIB_COSTUMES: Record<string, any> = Object.assign({{}}, {', '.join('(' + m + ' as any).COSTUMES || {}' for m in maps) or '{}'});\n")
json.dump(dict(sorted(lib.items())), open('library.json', 'w'), indent=1)
k = {x: sum(1 for v in lib.values() if v['kind'] == x) for x in ('core', 'tool', 'sample', 'episode')}
print(f"library.json: {len(lib)} entries · core {k['core']} · tool {k['tool']} · sample {k['sample']} · drawn for films {k['episode']}")
